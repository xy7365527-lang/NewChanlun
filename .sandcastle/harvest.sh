#!/usr/bin/env bash
# harvest.sh - sandcastle branch auto-acceptance (#1003 orchestrator gate, scripted)
# verify -> cherry-pick -> push -> close. Red => skip+report. Pure ASCII (bash 3.2).
# git 2.50.1 notes: cherry-pick has NO -q flag; use plain cherry-pick, capture rc directly.
# #1098: rc capture fix + empty-result (equivalent) detection + post-push recreated-sha check
#        + fail-loud (harvest-failures.md + macOS popup + exit 1). Stop-on-fail loop:
#        npx tsx .sandcastle/main.mts && bash .sandcastle/harvest.sh || break
set -euo pipefail
REPO=/Users/silencehan/Projects/NewChanlun
WT=/tmp/harvest
SKIP_ISSUES="${SKIP_ISSUES:-1024 1025}"

cd "$REPO"
git fetch origin main -q
if ! git -C "$WT" rev-parse --git-dir >/dev/null 2>&1; then git worktree add -q "$WT" main; fi
git -C "$WT" fetch -q origin main
git -C "$WT" reset -q --hard origin/main

harvested=0
failed=0
fail_list=""
for br in $(git branch --list 'sandcastle/issue-*' --format='%(refname:short)' | sort -t- -k3 -n); do
  n="${br##*-}"
  if [[ " $SKIP_ISSUES " == *" $n "* ]]; then echo "SKIP $br (skip-list)"; continue; fi
  st=$(gh issue view "$n" --json state --jq .state 2>/dev/null) || true
  if [ -z "$st" ]; then echo "SKIP $br (state read failed, retry later)"; continue; fi
  if [ "$st" = "CLOSED" ]; then git branch -qD "$br" >/dev/null 2>&1 || true; continue; fi
  if git merge-base --is-ancestor "$br" origin/main 2>/dev/null; then
    git branch -qD "$br" >/dev/null 2>&1 || true; continue
  fi
  shas=$(git rev-list --reverse origin/main.."$br")
  if [ -z "$shas" ]; then echo "SKIP $br (no new commits)"; continue; fi
  ok=1
  applied=0
  equivalent=0
  applied_shas=""
  for sha in $shas; do
    head_before=$(git -C "$WT" rev-parse HEAD)
    # set -e: a bare failing cherry-pick would abort the whole script before rc is read;
    # `|| rc=$?` keeps both the exit code and the flow alive (old `|| true` made rc always 0).
    # Output is captured to detect empty/already-applied (content already in mirror via recreated sha).
    rc=0
    out=$(git -C "$WT" cherry-pick "$sha" 2>&1) || rc=$?
    if [ $rc = 0 ]; then
      applied=$((applied+1))
      applied_shas="$applied_shas $(git -C "$WT" rev-parse HEAD)"
      continue
    fi
    # rc != 0: classify the failure.
    if [ -n "$(git -C "$WT" ls-files -u 2>/dev/null)" ]; then
      git -C "$WT" cherry-pick --abort 2>/dev/null || git -C "$WT" reset -q --hard origin/main
      echo "FAIL $br (cherry-pick conflict: $sha)"; ok=0
      fail_list="${fail_list}${br} (cherry-pick conflict: ${sha})"$'\n'
      break
    fi
    if [ "$head_before" = "$(git -C "$WT" rev-parse HEAD)" ] && printf '%s' "$out" | grep -qiE 'empty|nothing to commit'; then
      # already-applied / empty result => content equivalent in mirror; skip this commit.
      git -C "$WT" cherry-pick --skip 2>/dev/null || git -C "$WT" reset -q --hard HEAD
      equivalent=$((equivalent+1))
      continue
    fi
    git -C "$WT" cherry-pick --abort 2>/dev/null || git -C "$WT" reset -q --hard origin/main
    echo "FAIL $br (cherry-pick failed: $sha)"; ok=0
    fail_list="${fail_list}${br} (cherry-pick failed: ${sha})"$'\n'
    break
  done
  if [ $ok = 0 ]; then
    failed=$((failed+1))
    git -C "$WT" reset -q --hard origin/main
    continue
  fi
  # All commits equivalent (nothing applied): content already in mirror; close + delete branch, nothing pushed.
  if [ $applied = 0 ] && [ $equivalent -gt 0 ]; then
    flat=$(echo $shas | tr '\n' ' ')
    comment_done=0
    for attempt in 1 2 3; do
      gh issue comment "$n" --body "> *This was generated by AI during wayfinding.*

**Auto-accept (harvest.sh, #1003 gate scripted)**: sandcastle two-phase branch $br content already equivalent in mirror (commits $flat recreated in earlier rounds); nothing pushed; closing ticket." >/dev/null && { comment_done=1; break; }
      sleep 5
    done
    [ $comment_done = 1 ] || echo "WARN $br (comment failed 3x, closing anyway)"
    gh issue close "$n" >/dev/null
    echo "HARVESTED $br -> main (equivalent, nothing pushed)"
    harvested=$((harvested+1))
    git branch -qD "$br" >/dev/null 2>&1 || true
    continue
  fi
  if [ $ok = 1 ] && ! (cd "$WT/rust" && CARGO_TARGET_DIR=/tmp/harvest-t cargo test --lib >/dev/null 2>&1); then echo "FAIL $br (lib tests red)"; ok=0; fail_list="${fail_list}${br} (lib tests red)"$'\n'; fi
  if [ $ok = 1 ] && ! (cd "$WT/rust" && CARGO_TARGET_DIR=/tmp/harvest-t cargo fmt --check >/dev/null 2>&1); then echo "FAIL $br (fmt drift)"; ok=0; fail_list="${fail_list}${br} (fmt drift)"$'\n'; fi
  if [ $ok = 1 ] && ! (cd "$WT/rust" && CARGO_TARGET_DIR=/tmp/harvest-t cargo check --all-targets >/dev/null 2>&1); then echo "FAIL $br (check red)"; ok=0; fail_list="${fail_list}${br} (check red)"$'\n'; fi
  if [ $ok = 1 ] && ! (cd "$WT/rust" && CARGO_TARGET_DIR=/tmp/harvest-t cargo check --all-targets --features backtest_bin >/dev/null 2>&1); then echo "FAIL $br (backtest_bin check red)"; ok=0; fail_list="${fail_list}${br} (backtest_bin check red)"$'\n'; fi
  if [ $ok = 1 ] && ! git -C "$WT" push -q origin main:main; then echo "FAIL $br (push)"; ok=0; fail_list="${fail_list}${br} (push)"$'\n'; fi
  # post-push: verify the shas this round's cherry-picks produced are in the mirror.
  # Raw branch shas are recreated by cherry-pick, so they can never be ancestors of origin/main.
  if [ $ok = 1 ]; then
    git fetch origin main -q
    for asha in $applied_shas; do
      if ! git merge-base --is-ancestor "$asha" origin/main 2>/dev/null; then
        echo "FAIL $br (post-push ancestor check: recreated sha $asha not in origin/main, will NOT close ticket)"; ok=0
        fail_list="${fail_list}${br} (post-push ancestor check)"$'\n'
        break
      fi
    done
  fi
  if [ $ok = 1 ]; then
    flat=$(echo $shas | tr '\n' ' ')
    comment_done=0
    for attempt in 1 2 3; do
      gh issue comment "$n" --body "> *This was generated by AI during wayfinding.*

**Auto-accept (harvest.sh, #1003 gate scripted)**: sandcastle two-phase branch $br green (lib full / fmt / check both feature sets); commits $flat merged and pushed to main." >/dev/null && { comment_done=1; break; }
      sleep 5
    done
    [ $comment_done = 1 ] || echo "WARN $br (comment failed 3x, closing anyway)"
    gh issue close "$n" >/dev/null
    echo "HARVESTED $br -> main"
    harvested=$((harvested+1))
    git branch -qD "$br" >/dev/null 2>&1 || true
  else
    failed=$((failed+1))
    git -C "$WT" reset -q --hard origin/main
  fi
done

# fail-loud (#1098): on any failure append a failure ledger + macOS popup + exit 1,
# so a red harvest cannot silently repeat round after round.
if [ $failed -gt 0 ]; then
  mkdir -p .sandcastle/logs
  {
    echo "## harvest failed ($(date '+%Y-%m-%d %H:%M:%S'))"
    echo
    echo "harvested=$harvested failed=$failed"
    echo
    echo "failed branches:"
    printf '%s' "$fail_list" | sed '/^$/d; s/^/- /'
    echo
  } >> .sandcastle/logs/harvest-failures.md
  osascript -e "display notification \"Sandcastle harvest: ${failed} failed\" with title \"harvest.sh FAIL\"" 2>/dev/null || true
  exit 1
fi
echo "harvest done: harvested=$harvested failed=$failed"
