fn fixture_bars() -> Vec<Bar> {
    BTC_HEAD_5_140
        .iter()
        .enumerate()
        .map(|(k, &(high, low))| Bar {
            source_index: 5 + k,
            timestamp: (5 + k) as i64 * 60_000,
            open: low,
            high,
            low,
            close: high,
            volume: 0.0,
            untradable: false,
        })
        .collect()
}

fn anchor_high_low(bars: &[Bar]) -> Vec<(usize, Tick, Tick)> {
    bars.iter()
        .map(|b| (b.source_index, b.high, b.low))
        .collect()
}

#[test]
fn issue1634_btc_file_head_flat_prefix_does_not_collapse_to_one_group() {
    let bars = fixture_bars();
    // 触发前提：首对 raw 互含（恒价），且其后确有相邻 raw 非包含严格对。
    assert!(contains(&bars[0], &bars[1]), "夹具须以互含首对起头");
    assert!(
        bars.windows(2).any(|w| !contains(&w[0], &w[1])),
        "夹具须含相邻 raw 非包含严格对"
    );
    let config = ThetaConfig::default();

    let layer = parse_layer(&bars, &config);
    assert_eq!(
        anchor_high_low(&layer.merged_bars),
        EXPECTED_MERGED.to_vec(),
        "紧凑入口 parse_layer 须按正本自 0 折叠（main 上为单组）"
    );
    // 旧批量核同一规则（首个非包含严格对定方向、自 0 折叠），逐字段对拍。
    assert_eq!(*layer.merged_bars, process_inclusion(&bars).merged);

    let (facts_layer, facts) = parse_layer_with_inclusion_facts(&bars, &config);
    assert_eq!(facts_layer, layer, "完整事实入口与紧凑入口同输出");
    assert!(
        !facts.initial_direction_unsettled,
        "严格对已出现，不得仍处未定"
    );

    let mut state = IncrFactsState::empty();
    for bar in &bars {
        state.append(*bar);
    }
    assert!(!state.unsettled());
    let (group_layer, evidence) = parse_layer_with_group_evidence(&state, &config);
    assert_eq!(group_layer, layer, "S 生产入口与紧凑入口同输出");
    assert_eq!(evidence.groups.len(), EXPECTED_MERGED.len());
}

/// 全史读数锁（需数据文件，默认忽略）：`NC_BTC_FULL_JSON=<btc_1m_full.json> cargo test --release --lib
/// issue1634 -- --ignored`。期望组数取自独立 Python 实现（见模块头）。
#[test]
#[ignore = "需要 btc_1m_full.json（NC_BTC_FULL_JSON）"]
fn issue1634_full_history_from_file_head_matches_independent_oracle() {
    let path = std::env::var("NC_BTC_FULL_JSON").expect("设置 NC_BTC_FULL_JSON");
    let config = ThetaConfig::default();
    let all = super::super::backtest::data::load_symbol(
        std::path::Path::new(&path),
        "BTCUSDT-1m",
        &config,
        60,
    )
    .expect("load_symbol")
    .bars;
    assert_eq!(all.len(), 4_613_599);
    for (start, expected) in [(0usize, 3_037_868usize), (5, 3_037_866), (104, 3_037_848)] {
        let bars = &all[start..];
        let layer = parse_layer(bars, &config);
        println!(
            "start={start} merged={} fractals={} strokes={} segments={}",
            layer.merged_bars.len(),
            layer.fractals.len(),
            layer.strokes.len(),
            layer.segments.len()
        );
        assert_eq!(layer.merged_bars.len(), expected, "start={start}");
        assert_eq!(
            *layer.merged_bars,
            process_inclusion(bars).merged,
            "start={start}"
        );
    }
}
