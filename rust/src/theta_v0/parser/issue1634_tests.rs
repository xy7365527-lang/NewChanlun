//! #1634 回归锁：BTC 全史数据文件首段（平盘、零量、首对互含）从文件首根起解析不得坍缩为单组。
//!
//! 成因（#1634 诊断）：main 的紧凑/完整事实包含状态（`IncrFactsState::append`、
//! `process_inclusion_with_facts`）在首对 raw 互含时置 `initial_direction_unsettled` 并**永久**等待，
//! 之后再出现的相邻 raw 非包含严格对也不解锁 ⟹ `merged=1 fractals=0 strokes=0`。这违背
//! `.chanlun/definitions/baohan.md`「初始方向」（#1342 裁定，v1.5 起）：首个相邻 raw 非包含严格对出现的
//! cut，以其方向自序号 0 左折叠并发布；#1342 受影响代码清单已点名该处（「紧凑状态的永久 unsettled
//! （`:843` 遇包含即停）→ 非包含对出现即解锁并自起点重折」，归 #1393）。本文件锁 #1393 W 实装在
//! 真实数据形态上的结果。
//!
//! 夹具 = `btc_1m_full.json`（sha256 `16ea13d5…707b`，4,613,599 根）下标 5..=140 的 high/low，按
//! 默认 tick 1e-8 量化（`types::quantize`）；下标 5 = #1629 `W=4,613,599` 窗口首根。
//! 期望序列 `EXPECTED_MERGED` 由独立 Python 实现（逐字按 baohan.md：首个相邻 raw 非包含严格对定
//! 初始方向，自 0 左折叠；`contains`/`strict_dir`/上下合并同正本）算出，不取自 Rust；同一实现
//! 在起点 104 全史得 3,037,848 组，与 main 实测（#1629 `degenerate-window-probe`）逐数相同。

